const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../Code.gs'), 'utf8');
const cache = new Map();
const properties = new Map();
let migrations = 0;
let setups = 0;
let locks = 0;
let releases = 0;
let failMigration = false;
const context = {
  CacheService: { getScriptCache: () => ({ get: key => cache.get(key) || null, put: (key, value) => cache.set(key, value), remove: key => cache.delete(key) }) },
  PropertiesService: { getScriptProperties: () => ({ getProperty: key => properties.get(key) || null, setProperty: (key, value) => properties.set(key, value), deleteProperty: key => properties.delete(key) }) },
  LockService: { getScriptLock: () => ({ tryLock: () => { locks++; return true; }, releaseLock: () => releases++ }) }
};
vm.createContext(context);
vm.runInContext(source, context);
context.ensureTable_ = () => setups++;
context.getSheet_ = () => ({ appendRow() {} });
context.readTable_ = () => [];
context.clearTableCache_ = () => {};
context.clearAllTableCaches_ = () => {};
context.getOrCreateRootFolder_ = () => {};
context.migrateLegacyMaterials_ = () => { migrations++; if (failMigration) throw new Error('migration failed'); };
context.ensureDatabase_();
assert.equal(migrations, 1);
assert.ok(setups > 0);
assert.ok(properties.has('DATABASE_SCHEMA_READY'));
const originalSetups = setups;
cache.clear();
context.ensureDatabase_();
assert.equal(migrations, 1, 'Cache eviction must not trigger schema migration');
assert.equal(setups, originalSetups);
assert.equal(locks, 1, 'An initialized database must not acquire a global write lock');
properties.set('DATABASE_SCHEMA_READY', 'old-schema');
cache.clear();
context.ensureDatabase_();
assert.equal(migrations, 2, 'Schema upgrades must still run');
context.setSpreadsheetId('different-sheet');
context.ensureDatabase_();
assert.equal(migrations, 3, 'Changing the database must initialize the new database');
context.initDatabase();
assert.equal(migrations, 4, 'Explicit initialization must still repair tables');
cache.clear(); properties.delete('DATABASE_SCHEMA_READY'); failMigration = true;
assert.throws(() => context.ensureDatabase_(), /migration failed/);
assert.equal(properties.has('DATABASE_SCHEMA_READY'), false, 'Failed migrations must not be marked complete');
assert.equal(locks, releases);
console.log('PASS schema: cache eviction, upgrade, database switch, explicit repair, failure and lock release');

let fullCalls = 0;
const shared = { boardId: 'board', materialId: 'material', updatedAt: 'state-v1' };
context.getBoard_ = () => ({ id: 'board' });
context.readClassroomPulseCache_ = key => key.endsWith('_state') ? JSON.stringify(shared) : key.endsWith('_catalog') ? 'catalog-v1' : key.endsWith('_token') ? 'pulse-v1' : 'ink-v1';
context.classroomSync_ = () => { fullCalls++; return { ok: true, state: shared, stateVersion: 'state-v1', catalogVersion: 'catalog-v1', inkChanged: true, ink: [], materials: [] }; };
context.now_ = () => 'now';
const payload = { boardId: 'board', materialId: 'material', inkPage: 1, includeChanges: '1', includeSubmissionCounts: '0', catalogVersion: 'catalog-v1', stateVersion: 'state-v1', inkVersion: 'ink-v1' };
const unchanged = context.classroomPulse_(payload);
assert.equal(fullCalls, 0);
assert.equal(unchanged.inkChanged, false);
const changed = context.classroomPulse_({ ...payload, inkVersion: 'old' });
assert.equal(fullCalls, 1);
assert.ok(Array.isArray(changed.ink));
const catalog = context.classroomPulse_({ ...payload, catalogVersion: 'old' });
assert.equal(catalog.catalogChanged, true);
context.classroomPulse_({ ...payload, includeChanges: '0', inkVersion: 'old' });
assert.equal(fullCalls, 2, 'Legacy clients must retain the lightweight response contract');
console.log('PASS sync: unchanged stays lightweight, changed data included once, catalog flags and legacy compatibility');
